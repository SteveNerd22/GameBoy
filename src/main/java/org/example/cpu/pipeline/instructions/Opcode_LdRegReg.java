package org.example.cpu.pipeline.instructions;

import org.example.cpu.Register;
import org.example.cpu.SM83;

@CpuOpcode(value = {
        0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x47,
        0x48, 0x49, 0x4A, 0x4B, 0x4C, 0x4D, 0x4F,
        0x50, 0x51, 0x52, 0x53, 0x54, 0x55, 0x57,
        0x58, 0x59, 0x5A, 0x5B, 0x5C, 0x5D, 0x5F,
        0x60, 0x61, 0x62, 0x63, 0x64, 0x65, 0x67,
        0x68, 0x69, 0x6A, 0x6B, 0x6C, 0x6D, 0x6F,
        0x78, 0x79, 0x7A, 0x7B, 0x7C, 0x7D, 0x7F
})
public final class Opcode_LdRegReg extends CpuInstruction {

    @Override
    protected boolean executeStep(int step, int opcode, SM83 cpu) {
        Register src = resolveSourceRegister(opcode, cpu);
        Register dest = resolveDestRegister(opcode, cpu);

        src.emitToInternalData();
        dest.sampleInternalData();
        cpu.PC.emit();

        return true;
    }
}